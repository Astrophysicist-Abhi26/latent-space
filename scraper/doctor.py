#!/usr/bin/env python3
"""
Test sources against the live sites, from your own machine.

  python scraper/doctor.py                   every enabled source: status, postings found, seconds
  python scraper/doctor.py --all             also parked sources (enabled: false)
  python scraper/doctor.py --only NCBS       only sources whose name contains a word
  python scraper/doctor.py --show NCBS       ... and print the postings they return
  python scraper/doctor.py --probe insitro   which public job board (Greenhouse, Lever, Ashby,
                                             Workable) answers for a company's board name
  python scraper/doctor.py --markdown        rewrite SOURCES.md from the YAML files

Statuses: ok · low (fewer than min_expected) · empty · error · robots (the site's
robots.txt asks tools like this not to read the page) · unverified (an unconfirmed
URL failed: fix it or set enabled: false).
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import scrape as S                     # noqa: E402
from sources_ats import probe          # noqa: E402

HOW = {"rss": "RSS feed", "euraxess": "EURAXESS search pages", "links": "job-link page", "listing": "notice page",
       "greenhouse": "Greenhouse API", "lever": "Lever API", "ashby": "Ashby API", "workable": "Workable API",
       "workday": "Workday search", "manual": "added by hand"}


def markdown(sources):
    lines = ["# Sources", "",
             "Every place Latent Space reads, grouped as on the site's **Sources** tab. Generated by",
             "`python scraper/doctor.py --markdown` from `scraper/sources.yaml`, `institutes.yaml` and",
             "`companies.yaml`. **Confirmed** = the URL or board was checked live (Nov 2026); **partly confirmed** =",
             "some of its URLs were checked, the rest follow the same pattern; **to confirm** = it follows the",
             "site's documented pattern but was not tested. An unconfirmed source that fails shows amber on the",
             "site, and `python scraper/doctor.py --probe <slug>` finds a company's right job board.", ""]
    groups = {}
    for s in sources:
        groups.setdefault(s.group, []).append(s)
    for group, items in groups.items():
        lines += [f"## {group}", "", "| Source | Read as | Status | Notes |", "|---|---|---|---|"]
        for s in items:
            url = s.url.replace("…", "")
            name = f"[{s.name}]({url})" if url.startswith("http") else s.name
            ver = s.cfg.get("verified")
            status = s.verification if s.enabled else "parked"
            note = " ".join(x for x in (s.cfg.get("note") or "", ver if isinstance(ver, str) else "") if x)
            lines.append(f"| {name} | {HOW.get(s.kind, s.kind)} | {status} | {str(note).replace('|', '/')} |")
        lines.append("")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--all", action="store_true", help="include parked sources")
    ap.add_argument("--only", help="only sources whose name contains this text")
    ap.add_argument("--show", help="like --only, and print the postings")
    ap.add_argument("--probe", help="company board name to try on every job-board API")
    ap.add_argument("--markdown", action="store_true", help="rewrite SOURCES.md")
    a = ap.parse_args(argv)
    if a.probe:
        print(f"Job boards answering for '{a.probe}':")
        for ats, result in probe(a.probe):
            print(f"  {ats:10s} {result if isinstance(result, str) else str(result) + ' postings'}")
        return 0
    sources = S.build_sources(include_disabled=a.all or a.markdown)
    if a.markdown:
        path = os.path.join(S.ROOT, "SOURCES.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write(markdown(sources))
        print("wrote", path)
        return 0
    word = a.show or a.only
    if word:
        sources = [s for s in sources if word.lower() in s.name.lower()]
    for src in sources:
        _, batch, status, error, secs = S.run_one(src)
        print(f"{status:10s} {len(batch):4d}  {secs:5.1f}s  {src.name}" + (f"  — {error}" if error else ""))
        if a.show:
            for j in batch[:25]:
                print(f"             · {j['title'][:80]} | {j.get('org', '')[:30]} | {j.get('location', '')[:25]}"
                      f" | deadline {j.get('deadline') or '-'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
